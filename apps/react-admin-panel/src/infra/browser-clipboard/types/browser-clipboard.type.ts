/**
 * Результат и действия браузерного копирования текста.
 */
export type BrowserClipboard = {
  /**
   * Копирует текст по действию пользователя.
   */
  copy: (text: string) => void
  /**
   * Последнее копирование подтверждено браузером.
   */
  copied: boolean
  /**
   * Причина последнего отказа.
   */
  error: Error | null
  /**
   * Сбрасывает результат и таймер подтверждения.
   */
  reset: () => void
}
