/**
 * Предусмотренные отказы действий с документами.
 */
const FILE_ERROR_MESSAGE = {
  /**
   * Локальная проверка недоступна.
   */
  HASH_UNAVAILABLE: 'Не удалось прочитать файл и вычислить SHA-256. Выберите файл ещё раз.',
  /**
   * Сервер получил другие байты.
   */
  HASH_MISMATCH: 'SHA-256 на сервере не совпал с выбранным файлом. Добавьте исходный файл заново.',
  /**
   * Доступ отозван или не предоставлен.
   */
  FORBIDDEN: 'Недостаточно прав для действия с файлами.',
  /**
   * Документ недоступен.
   */
  NOT_FOUND: 'Файл не найден. Обновите список.',
  /**
   * Неверный запрос или метаданные.
   */
  INVALID_INPUT: 'Проверьте имя файла, папку и теги.',
  /**
   * Неверный размер передачи.
   */
  SIZE_MISMATCH: 'Файл передан не полностью или его размер изменился. Повторите передачу.',
  /**
   * Истёкшая попытка загрузки.
   */
  EXPIRED: 'Срок загрузки истёк. Повтор создаст новую попытку.',
  /**
   * Объект пока недоступен для подтверждения.
   */
  CONFLICT: 'Передача ещё не завершена. Повторите попытку.',
  /**
   * Сбой прямой передачи в S3.
   */
  UPLOAD_FAILED: 'Не удалось передать файл. Проверьте соединение и повторите попытку.',
  /**
   * Временный отказ API или хранилища.
   */
  UNAVAILABLE: 'Сервис временно недоступен. Повторите попытку.'
} as const

/**
 * Известная ошибка файлового сценария без технического ответа источника.
 */
export class FileError extends Error {
  constructor(readonly code: keyof typeof FILE_ERROR_MESSAGE) { super(code) }
}

/**
 * Распознаёт ожидаемую ошибку документа.
 */
export const isFileError = (error: unknown): error is FileError => error instanceof FileError

/**
 * Возвращает безопасное объяснение ошибки.
 */
export const getFileErrorMessage = (error: unknown): string => {
  return isFileError(error) ? FILE_ERROR_MESSAGE[error.code] : 'Действие не завершено. Попробуйте ещё раз.'
}
