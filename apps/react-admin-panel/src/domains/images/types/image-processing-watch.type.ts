/**
 * Подтверждённые этим экраном задания, за которыми нужно следить вне текущих фильтров.
 */
export type ImageProcessingWatch = {
  /**
   * Идентификаторы ещё не завершившихся загрузок и повторов.
   */
  pendingIds: readonly string[]
  /**
   * Удаляет только подтверждённые терминальные задания из наблюдения.
   */
  onSettled: (ids: readonly string[]) => void
}
